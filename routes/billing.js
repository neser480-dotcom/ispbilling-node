"use strict";

const express = require("express");

const controller =
    require("../controllers/billing.controller");

const {
    requireAuth
} = require("../middleware/auth");


const router =
    express.Router();


/*
|--------------------------------------------------------------------------
| ALL BILLING ROUTES REQUIRE LOGIN
|--------------------------------------------------------------------------
*/

router.use(
    requireAuth
);


/*
|--------------------------------------------------------------------------
| REGISTRATION INVOICES
|--------------------------------------------------------------------------
|
| /billing
|
|--------------------------------------------------------------------------
*/

router.get(
    "/",
    controller.index
);


/*
|--------------------------------------------------------------------------
| INVOICE DETAILS
|--------------------------------------------------------------------------
|
| /billing/invoice/123
|
|--------------------------------------------------------------------------
*/

router.get(
    "/invoice/:id",
    controller.details
);


/*
|--------------------------------------------------------------------------
| SSL COMMERZ CONFIGURATION
|--------------------------------------------------------------------------
|
| /billing/pay
|
| Only Super Admin.
|
|--------------------------------------------------------------------------
*/

router.get(
    "/pay",
    controller.pay
);


/*
|--------------------------------------------------------------------------
| INVOICE DATA
|--------------------------------------------------------------------------
|
| GET /billing/data
|
|--------------------------------------------------------------------------
*/

router.get(
    "/data",
    controller.data
);


/*
|--------------------------------------------------------------------------
| SINGLE INVOICE DATA
|--------------------------------------------------------------------------
|
| GET /billing/data/:id
|
|--------------------------------------------------------------------------
*/

router.get(
    "/data/:id",
    controller.invoiceData
);


module.exports = router;