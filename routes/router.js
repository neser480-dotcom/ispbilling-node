"use strict";

const express = require("express");

const router =
    express.Router();

const controller =
    require("../controllers/router.controller");

const {
    requireAuth
} =
    require("../middleware/auth");


/*
|--------------------------------------------------------------------------
| AUTH
|--------------------------------------------------------------------------
*/

router.use(requireAuth);


/*
|--------------------------------------------------------------------------
| ROUTER LIST
|--------------------------------------------------------------------------
*/

router.get(
    "/",
    controller.list
);


/*
|--------------------------------------------------------------------------
| ADD ROUTER
|--------------------------------------------------------------------------
*/

router.post(
    "/",
    controller.create
);


/*
|--------------------------------------------------------------------------
| UPDATE ROUTER
|--------------------------------------------------------------------------
*/

router.put(
    "/:id",
    controller.update
);


/*
|--------------------------------------------------------------------------
| DELETE ROUTER
|--------------------------------------------------------------------------
*/

router.delete(
    "/:id",
    controller.remove
);


/*
|--------------------------------------------------------------------------
| CHECK CONNECTION
|--------------------------------------------------------------------------
*/

router.get(
    "/:id/check",
    controller.check
);


/*
|--------------------------------------------------------------------------
| ROUTER HISTORY / DETAILS
|--------------------------------------------------------------------------
*/

router.get(
    "/:id/history",
    controller.history
);


/*
|--------------------------------------------------------------------------
| ROUTER PACKAGES
|--------------------------------------------------------------------------
*/

router.get(
    "/:id/packages",
    controller.packages
);


/*
|--------------------------------------------------------------------------
| PACKAGE SYNC
|--------------------------------------------------------------------------
*/

router.post(
    "/:id/packages/sync",
    controller.packageSync
);


/*
|--------------------------------------------------------------------------
| PACKAGE UPDATE
|--------------------------------------------------------------------------
*/

router.put(
    "/packages/:id",
    controller.packageUpdate
);


/*
|--------------------------------------------------------------------------
| PACKAGE DELETE
|--------------------------------------------------------------------------
*/

router.delete(
    "/packages/:id",
    controller.packageDelete
);


/*
|--------------------------------------------------------------------------
| CUSTOMER SYNC
|--------------------------------------------------------------------------
*/

router.post(
    "/:id/customers/sync",
    controller.customerSync
);


/*
|--------------------------------------------------------------------------
| ACTIVE CUSTOMERS
|--------------------------------------------------------------------------
*/

router.get(
    "/:id/customers",
    controller.activeCustomers
);


module.exports = router;